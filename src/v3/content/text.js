// باغ قصه‌ها ۳ — ابزارهای متنیِ فارسی (بدون وابستگی به مرورگر تا در آزمونِ node هم اجرا شود)

/** حرف‌هایی که روی صفحه‌کلیدِ فارسیِ برنامه هست */
export const PERSIAN_LETTERS='آابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی'.split('');

/**
 * متن را به همان حرف‌هایی که کودک می‌تواند روی صفحه‌کلید بزند تبدیل می‌کند:
 * نیم‌فاصله، اِعراب، «،» و «ؤ/ة/ي/ك/أ» حذف یا جانشین می‌شوند.
 * بدون این کار، رمزگشاییِ بیشترِ جمله‌ها باز نمی‌شد.
 */
export const normalizePlain=text=>String(text)
  .replace(/[\u200b\u200c\u200d\u200e\u200f]/g,'')
  .replace(/[\u064b-\u0652\u0670\u0640\u0653-\u0655]/g,'')
  .replace(/ي/g,'ی').replace(/ك/g,'ک').replace(/[أإآٱ]/g,'آ').replace(/ؤ/g,'و').replace(/ة/g,'ه')
  .split('').filter(ch=>ch===' '||PERSIAN_LETTERS.includes(ch)).join('')
  .replace(/\s+/g,' ').trim();
